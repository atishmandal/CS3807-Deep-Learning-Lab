def plot_history(hist, fname, title, keys=(("loss", "val_loss"),), ylabels=("Reconstruction loss",)):
    fig, axes = plt.subplots(1, len(keys), figsize=(5.5 * len(keys), 4), squeeze=False)
    for ax, (tr, va), yl in zip(axes[0], keys, ylabels):
        ax.plot(hist.history[tr], label="Training")
        ax.plot(hist.history[va], label="Validation")
        ax.set_xlabel("Epoch")
        ax.set_ylabel(yl)
        ax.legend()
