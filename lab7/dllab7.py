def recon_metrics(x, xhat):

    x = np.asarray(x, dtype="float32").reshape(-1, 28, 28)
    xhat = np.asarray(xhat, dtype="float32").reshape(-1, 28, 28)
    return {
        "MSE": float(np.mean((x - xhat) ** 2)),
        "MAE": float(np.mean(np.abs(x - xhat))),
        "SSIM": float(np.mean([structural_similarity(a, b, data_range=1.0) for a, b in zip(x, xhat)])),
    }


def per_image_error(x, xhat):

    return np.mean((x.reshape(len(x), -1) - xhat.reshape(len(xhat), -1)) ** 2, axis=1)


