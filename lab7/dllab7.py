def add_gaussian(x, sigma, r):
    return np.clip(x + r.normal(0.0, sigma, x.shape), 0.0, 1.0).astype("float32")


def add_salt_pepper(x, p, r):

    x = x.copy()
    corrupt = r.random(x.shape) < p
    salt = r.random(x.shape) < 0.5
    x[corrupt & salt] = 1.0
    x[corrupt & ~salt] = 0.0
    return x.astype("float32")


