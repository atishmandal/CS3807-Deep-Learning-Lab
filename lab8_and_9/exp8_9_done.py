class AttentionStage(layers.Layer):
    def __init__(self, act_layer, att_layer, **kw):
        super().__init__(**kw); self.act = act_layer; self.att = att_layer
    def call(self, x):
        return self.att(self.act(x))
    def compute_output_shape(self, s):
        return s

def _clone_layer(layer):
    return layer.__class__.from_config(layer.get_config())

def build_model(cfg):
    base = ResNet50(weights="imagenet", include_top=False, input_shape=(IMG_SIZE, IMG_SIZE, 3))
    out_to_pos = {POS[p][1]: p for p in cfg}

    def clone_fn(layer):
        new = _clone_layer(layer)
        if layer.name in out_to_pos:
            p = out_to_pos[layer.name]
            return AttentionStage(new, ATTENTION[cfg[p]](), name=f"att_{p}")
        return new

    base_c = tf.keras.models.clone_model(base, clone_function=clone_fn)
    for l in base.layers:
        if l.weights:
            base_c.get_layer(l.name).set_weights(l.get_weights())
    x = layers.GlobalAveragePooling2D(name="gap")(base_c.output)
    x = layers.Dropout(DROPOUT, name="dropout")(x)
    out = layers.Dense(NUM_CLASSES, activation="softmax", name="classifier")(x)
    del base
    return Model(base_c.input, out)

