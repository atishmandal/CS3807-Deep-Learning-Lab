def overlay(img, heat, alpha=0.45):
    h = norm01(up(heat)) if np.asarray(heat).shape[:2] != (IMG_SIZE, IMG_SIZE) else norm01(heat)
    return np.clip((1 - alpha) * img / 255.0 + alpha * plt.cm.jet(h)[..., :3], 0, 1)

