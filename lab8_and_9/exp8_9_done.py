def _backbone_of(model):
    candidates = [l for l in model.layers if isinstance(l, tf.keras.Model)]
    if not candidates:
        return model
    return candidates[0]

def attention_info(model, pos, x):
    backbone = _backbone_of(model)
    feat_model = Model(backbone.input, backbone.get_layer(POS[pos][0]).output)
    F = tf.nn.relu(feat_model(x, training=False))
    stage = backbone.get_layer(f"att_{pos}")
    att = stage.att
    return F, att(F), att.get_maps(F)

def check_shapes(model, cfg):
    log = {}
    x = tf.zeros((1, IMG_SIZE, IMG_SIZE, 3))
    for p in cfg:
        F, Fa, _ = attention_info(model, p, x)
        assert F.shape == Fa.shape, "Attention changed the feature shape!"
        log[p] = {"before": list(F.shape[1:]), "after": list(Fa.shape[1:])}
        print(f"   {p}: before {log[p]['before']} -> after {log[p]['after']}")
    return log

def set_phase(model, phase):
    backbone = _backbone_of(model)
    backbone.trainable = True
    for layer in backbone.layers:
        if isinstance(layer, AttentionStage):
            layer.trainable = True
        elif phase == 1:
            layer.trainable = False
        else:
            layer.trainable = layer.name.startswith("conv5_") and not isinstance(
                layer, layers.BatchNormalization
            )
    for name in ("gap", "dropout", "classifier"):
        model.get_layer(name).trainable = True

def compile_model(model, lr):
    model.compile(optimizer=tf.keras.optimizers.Adam(lr),
                  loss=tf.keras.losses.CategoricalCrossentropy(),
                  metrics=["accuracy"])

def n_trainable(model):
    return int(sum(np.prod(w.shape) for w in model.trainable_weights))

def time_inference(model, reps=3):
    batches = [x for x, _ in test_ds]
    model(batches[0], training=False)
    times = []
    for _ in range(reps):
        t0 = time.perf_counter()
        for x in batches:
            _ = model(x, training=False).numpy()
        times.append((time.perf_counter() - t0) / len(y_test))
    return 1000.0 * float(np.median(times))

def evaluate_model(model):
    probs = model.predict(test_ds, verbose=0)
    y_pred = probs.argmax(1)
    p, r, f1, _ = precision_recall_fscore_support(y_test, y_pred, average="macro", zero_division=0)
    loss, acc = model.evaluate(test_ds, verbose=0)
    return {"test_acc": float(accuracy_score(y_test, y_pred)), "test_loss": float(loss),
            "precision": float(p), "recall": float(r), "f1": float(f1),
            "infer_ms": time_inference(model), "y_pred": y_pred.tolist()}

