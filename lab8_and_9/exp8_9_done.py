def collect(name, idx):
    model = load_trained(name)
    x = preprocess_input(X_test[idx].astype(np.float32))
    out = {"pred": model(x, training=False).numpy().argmax(1), "cam": gradcam(model, x), "att": {}}
    for p in EXPERIMENTS[name]:
        F, Fa, maps = attention_info(model, p, x)
        out["att"][p] = {"F": F.numpy(), "Fa": Fa.numpy(), "maps": {k: v.numpy() for k, v in maps.items()}}
    del model; tf.keras.backend.clear_session(); gc.collect()
    return out

