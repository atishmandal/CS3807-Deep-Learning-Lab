def run_experiment(name):
    if name in RESULTS:
        print(f"[skip] {name} already done"); return
    print(f"\n===== {name}  cfg={EXPERIMENTS[name]} =====")
    tf.keras.backend.clear_session(); gc.collect()
    tf.keras.utils.set_random_seed(SEED)
    cfg = EXPERIMENTS[name]
    model = build_model(cfg)
    shapes = check_shapes(model, cfg)

    set_phase(model, 1); compile_model(model, LR_HEAD)
    trainable_p1 = n_trainable(model)
    h1 = model.fit(train_ds, validation_data=val_ds, epochs=EPOCHS_HEAD, verbose=2)

    set_phase(model, 2); compile_model(model, LR_FT)
    h2 = model.fit(train_ds, validation_data=val_ds, epochs=EPOCHS_FT, verbose=2)

    hist = {k: [float(v) for v in h1.history[k] + h2.history[k]]
            for k in ("accuracy", "val_accuracy", "loss", "val_loss")}
    res = evaluate_model(model)
    res.update({
        "config": cfg, "history": hist, "finetune_start": EPOCHS_HEAD, "shapes": shapes,
        "total_params": int(model.count_params()),
        "trainable_params": n_trainable(model),
        "trainable_params_phase1": trainable_p1,
        "attention_params": int(sum(l.att.count_params() for l in _backbone_of(model).layers
                                    if isinstance(l, AttentionStage))),
        "train_acc": hist["accuracy"][-1], "val_acc": hist["val_accuracy"][-1],
    })
    model.save_weights(f"{OUT}/weights/{name}.weights.h5")
    RESULTS[name] = res
    json.dump(RESULTS, open(RESULTS_PATH, "w"))
    print(f"   test acc={res['test_acc']:.4f}  macroF1={res['f1']:.4f}  "
          f"params={res['total_params']:,}  att params={res['attention_params']:,}  "
          f"{res['infer_ms']:.2f} ms/img")
    del model; tf.keras.backend.clear_session(); gc.collect()

