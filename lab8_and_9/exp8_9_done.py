def norm01(a):
    a = np.asarray(a, np.float32); return (a - a.min()) / (a.max() - a.min() + 1e-8)

def up(a2d):
    return tf.image.resize(np.asarray(a2d, np.float32)[..., None], (IMG_SIZE, IMG_SIZE),
                           method="bilinear").numpy()[..., 0]

def gradcam(model, x):
    gm = Model(model.input, [model.get_layer("gap").input, model.output])
    with tf.GradientTape() as tape:
        fmap, preds = gm(x, training=False)
        cls = tf.argmax(preds, axis=1)
        score = tf.reduce_sum(preds * tf.one_hot(cls, NUM_CLASSES), axis=1)
    grads = tape.gradient(score, fmap)
    alpha = tf.reduce_mean(grads, axis=(1, 2))
    cam = tf.nn.relu(tf.reduce_sum(fmap * alpha[:, None, None, :], axis=-1)).numpy()
    return np.stack([norm01(up(c)) for c in cam])

def load_trained(name):
    model = build_model(EXPERIMENTS[name])
