class ChannelAttention(layers.Layer):
    def __init__(self, ratio=16, **kw):
        super().__init__(**kw); self.ratio = ratio
    def build(self, s):
        C = s[-1]
        self.fc1 = layers.Dense(max(C // self.ratio, 1), activation="relu")
        self.fc2 = layers.Dense(C, activation="sigmoid")
        self.fc1.build((None, C)); self.fc2.build((None, max(C // self.ratio, 1)))
        super().build(s)
    def channel_map(self, F):
        return self.fc2(self.fc1(tf.reduce_mean(F, axis=[1, 2])))
    def call(self, F):
        return F * self.channel_map(F)[:, None, None, :]
    def get_maps(self, F):
        return {"channel": self.channel_map(F)}

class SpatialAttention(layers.Layer):
    def __init__(self, kernel_size=7, **kw):
        super().__init__(**kw); self.k = kernel_size
    def build(self, s):
        self.conv = layers.Conv2D(1, self.k, padding="same", activation="sigmoid")
        self.conv.build((None, s[1], s[2], 2))
        super().build(s)
    def spatial_map(self, F):
        avg = tf.reduce_mean(F, axis=-1, keepdims=True)
        mx  = tf.reduce_max(F, axis=-1, keepdims=True)
        return self.conv(tf.concat([avg, mx], axis=-1))
    def call(self, F):
        return F * self.spatial_map(F)
    def get_maps(self, F):
        return {"spatial": self.spatial_map(F)}

class ChannelSpatial(layers.Layer):
    def __init__(self, order="cs", kernel_size=7, ratio=16, **kw):
        super().__init__(**kw); self.order = order
        self.ca = ChannelAttention(ratio); self.sa = SpatialAttention(kernel_size)
    def build(self, s):
        self.ca.build(s); self.sa.build(s); super().build(s)
    def call(self, F):
        if self.order == "cs":
            return self.sa(self.ca(F))
        return self.ca(self.sa(F))
    def get_maps(self, F):
        if self.order == "cs":
            Fc = self.ca(F)
            return {"channel": self.ca.channel_map(F), "spatial": self.sa.spatial_map(Fc)}
        Fs = self.sa(F)
        return {"spatial": self.sa.spatial_map(F), "channel": self.ca.channel_map(Fs)}

class SelfAttention(layers.Layer):
    def __init__(self, d_ratio=8, **kw):
        super().__init__(**kw); self.d_ratio = d_ratio
    def build(self, s):
        self.H, self.W, self.C = s[1], s[2], s[3]
        self.d = max(self.C // self.d_ratio, 1)
        self.wq = layers.Dense(self.d, use_bias=False)
        self.wk = layers.Dense(self.d, use_bias=False)
        self.wv = layers.Dense(self.C, use_bias=False)
        for l, out in ((self.wq, self.C), (self.wk, self.C), (self.wv, self.C)):
            l.build((None, self.H * self.W, out))
        self.gamma = self.add_weight(name="gamma", shape=(), initializer="zeros", trainable=True)
        super().build(s)
    def _attend(self, F):
        B = tf.shape(F)[0]
        X = tf.reshape(F, [B, self.H * self.W, self.C])
        Q, K, V = self.wq(X), self.wk(X), self.wv(X)
        A = tf.nn.softmax(tf.matmul(Q, K, transpose_b=True) /
                          tf.sqrt(tf.cast(self.d, F.dtype)), axis=-1)
        return A, tf.matmul(A, V)
    def call(self, F):
        _, Y = self._attend(F)
        return F + self.gamma * tf.reshape(Y, tf.shape(F))
    def get_maps(self, F):
        A, _ = self._attend(F)
        B = tf.shape(F)[0]
        mean = tf.reshape(tf.reduce_mean(A, axis=1), [B, self.H, self.W])
        mx   = tf.reshape(tf.reduce_max(A, axis=1), [B, self.H, self.W])
        return {"self_mean": mean, "self_max": mx, "self_A": A}

class CombinedAttention(layers.Layer):
    def __init__(self, **kw):
        super().__init__(**kw)
        self.cs = ChannelSpatial("cs", 7); self.sa = SelfAttention()
    def build(self, s):
        self.cs.build(s); self.sa.build(s); super().build(s)
    def call(self, F):
        return self.sa(self.cs(F))
    def get_maps(self, F):
        m = self.cs.get_maps(F); m.update(self.sa.get_maps(self.cs(F))); return m

class ECA(layers.Layer):
    def build(self, s):
        C = s[-1]
        k = int(abs((math.log2(C) + 1) / 2)); k = k if k % 2 else k + 1
        self.conv = layers.Conv1D(1, k, padding="same", use_bias=False)
        self.conv.build((None, C, 1)); super().build(s)
    def channel_map(self, F):
        z = tf.reduce_mean(F, axis=[1, 2])[:, :, None]
        return tf.sigmoid(self.conv(z))[:, :, 0]
    def call(self, F):
        return F * self.channel_map(F)[:, None, None, :]
    def get_maps(self, F):
        return {"channel": self.channel_map(F)}

class CBAM(layers.Layer):
    def __init__(self, ratio=16, kernel_size=7, **kw):
        super().__init__(**kw); self.ratio = ratio; self.sa = SpatialAttention(kernel_size)
    def build(self, s):
        C = s[-1]; h = max(C // self.ratio, 1)
        self.fc1 = layers.Dense(h, activation="relu"); self.fc2 = layers.Dense(C)
        self.fc1.build((None, C)); self.fc2.build((None, h)); self.sa.build(s)
        super().build(s)
    def channel_map(self, F):
        a = tf.reduce_mean(F, axis=[1, 2]); m = tf.reduce_max(F, axis=[1, 2])
        return tf.sigmoid(self.fc2(self.fc1(a)) + self.fc2(self.fc1(m)))
    def call(self, F):
        return self.sa(F * self.channel_map(F)[:, None, None, :])
    def get_maps(self, F):
        Fc = F * self.channel_map(F)[:, None, None, :]
        return {"channel": self.channel_map(F), "spatial": self.sa.spatial_map(Fc)}

class CoordAtt(layers.Layer):
    def __init__(self, ratio=32, **kw):
        super().__init__(**kw); self.ratio = ratio
    def build(self, s):
        self.H, self.W, C = s[1], s[2], s[3]; mip = max(8, C // self.ratio)
        self.conv1 = layers.Conv2D(mip, 1); self.bn = layers.BatchNormalization()
        self.conv_h = layers.Conv2D(C, 1, activation="sigmoid")
        self.conv_w = layers.Conv2D(C, 1, activation="sigmoid")
        self.conv1.build((None, self.H + self.W, 1, C)); self.bn.build((None, self.H + self.W, 1, mip))
        self.conv_h.build((None, self.H, 1, mip)); self.conv_w.build((None, self.W, 1, mip))
        super().build(s)
    def _att(self, F, training=False):
        xh = tf.reduce_mean(F, axis=2, keepdims=True)
        xw = tf.transpose(tf.reduce_mean(F, axis=1, keepdims=True), [0, 2, 1, 3])
        y = self.bn(self.conv1(tf.concat([xh, xw], axis=1)), training=training)
        y = y * tf.nn.relu6(y + 3.0) / 6.0
        yh, yw = tf.split(y, [self.H, self.W], axis=1)
        ah = self.conv_h(yh)
        aw = tf.transpose(self.conv_w(yw), [0, 2, 1, 3])
        return ah, aw
    def call(self, F, training=None):
        ah, aw = self._att(F, training); return F * ah * aw
    def get_maps(self, F):
        ah, aw = self._att(F)
        return {"spatial": tf.reduce_mean(ah * aw, axis=-1, keepdims=True)}

