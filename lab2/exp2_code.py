plt.show()


plt.figure(figsize=(10, 4))
cv_results = random_search.cv_results_
mean_scores = cv_results['mean_test_score']
params_labels = [f"Iter {i+1}" for i in range(len(mean_scores))]
plt.bar(params_labels, mean_scores, color='salmon', edgecolor='black')
